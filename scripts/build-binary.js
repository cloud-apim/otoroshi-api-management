#!/usr/bin/env bun
// Compiles the product into one executable: the server and its roles, the console and the portal
// (every file of dist/backoffice and dist/portal, embedded), the migrations, and the command line.
//
//   bun scripts/build-binary.js            this machine     -> dist/bin/otoroshi-apim
//   bun scripts/build-binary.js --all      linux and macos, x64 and arm64
//                                          -> dist/bin/otoroshi-apim-<os>-<arch>
//   bun scripts/build-binary.js --target bun-linux-arm64
//
// A target other than this machine needs the bun runtime of that target: bun downloads it.
// Run `bun run build` first (mise run build:binary does).

import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const DIST = join(ROOT, 'dist');
const OUT = join(DIST, 'bin');
const WORK = join(ROOT, 'node_modules', '.cache', 'otoroshi-apim-binary');
const TARGETS = ['bun-linux-x64', 'bun-linux-arm64', 'bun-darwin-x64', 'bun-darwin-arm64'];

const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : null;
};
const targets = argv.includes('--all') ? TARGETS : flag('--target') ? [flag('--target')] : [null];

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

for (const face of ['backoffice', 'portal']) {
  if (!existsSync(join(DIST, face, 'index.html'))) {
    console.error(`dist/${face} is not built: run \`bun run build\` (or mise run build:binary)`);
    process.exit(1);
  }
}

// the entry of the binary: every file of the two faces imported as a file — embedded by the
// compiler — and registered before the program starts
const embedded = ['backoffice', 'portal'].flatMap((face) => files(join(DIST, face)).map((path) => ({ key: relative(DIST, path).split('\\').join('/'), path })));
rmSync(WORK, { recursive: true, force: true });
mkdirSync(WORK, { recursive: true });
const entry = join(WORK, 'entry.js');
const spec = (path) => JSON.stringify(relative(WORK, path).split('\\').join('/').replace(/^(?!\.)/, './'));
writeFileSync(
  entry,
  [
    '// generated by scripts/build-binary.js',
    `import { embedUi } from ${spec(join(ROOT, 'server', 'ui-files.js'))};`,
    ...embedded.map((f, i) => `import f${i} from ${spec(f.path)} with { type: 'file' };`),
    `embedUi({ ${embedded.map((f, i) => `${JSON.stringify(f.key)}: f${i}`).join(', ')} });`,
    `await import(${spec(join(ROOT, 'server', 'bin.js'))});`,
    '',
  ].join('\n')
);

mkdirSync(OUT, { recursive: true });
for (const target of targets) {
  const outfile = join(OUT, target ? `otoroshi-apim-${target.replace(/^bun-/, '')}` : 'otoroshi-apim');
  const started = Date.now();
  const proc = Bun.spawnSync(['bun', 'build', '--compile', '--minify', '--sourcemap', ...(target ? [`--target=${target}`] : []), entry, '--outfile', outfile], { cwd: ROOT, stdout: 'pipe', stderr: 'pipe' });
  if (proc.exitCode !== 0) {
    console.error(proc.stdout.toString(), proc.stderr.toString());
    process.exit(proc.exitCode || 1);
  }
  const mb = (statSync(outfile).size / 1048576).toFixed(0);
  console.log(`${relative(ROOT, outfile)}  ${mb} MB, ${embedded.length} files of the faces embedded, ${((Date.now() - started) / 1000).toFixed(1)} s`);
}
