const KEY = 'apim.portal.lang';

function interpolate(s, vars) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

const I18nCtx = createContext(null);

export function I18nProvider({ defaultLanguage = 'en', children }) {
  const initial = (() => {
    try {
      const stored = localStorage.getItem(KEY);
      if (stored && dict[stored]) return stored;
    } catch (e) {}
    if (dict[defaultLanguage]) return defaultLanguage;
    const nav = (navigator.language || 'en').slice(0, 2);
    return dict[nav] ? nav : 'en';
  })();
  const [lang, setLangState] = useState(initial);
  const setLang = useCallback((l) => {
    setLangState(l);
    try {
      localStorage.setItem(KEY, l);
    } catch (e) {}
    document.documentElement.lang = l;
  }, []);
  const t = useCallback((key, vars) => interpolate(dict[lang]?.[key] ?? dict.en[key] ?? key, vars), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  // the components shared with the console (lists, dates) read their texts in the same language
  setLanguage(lang, shared);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  return useContext(I18nCtx);
}

export function useT() {
  return useContext(I18nCtx).t;
}

// a multilingual value { en: '...', fr: '...' } in the best available language
// a text of the portal settings — one string, or one per language — in the visitor's language
export function usePortalText(portal) {
  const { lang } = useI18n();
  return (value) => pickLang(value, lang, portal?.defaultLanguage);
}

export function pickLang(value, lang, fallback) {
  if (!value || typeof value !== 'object') return value || '';
  return value[lang] || (fallback && value[fallback]) || value.en || Object.values(value)[0] || '';
}

export function windowLabel(ms, lang) {
  const fr = lang === 'fr';
  if (!ms) return '';
  const units = [
    [86400000, fr ? 'jour' : 'day', fr ? 'jours' : 'days'],
    [3600000, fr ? 'heure' : 'hour', fr ? 'heures' : 'hours'],
    [60000, 'minute', 'minutes'],
    [1000, fr ? 'seconde' : 'second', fr ? 'secondes' : 'seconds'],
  ];
  for (const [u, one, many] of units) {
    if (ms % u === 0) return ms === u ? one : `${ms / u} ${many}`;
  }
  return `${ms} ms`;
}
